/**
 * iGEM Wiki Export API
 * Generates Markdown/HTML formatted reports ready for iGEM Wiki
 */

import { NextRequest, NextResponse } from 'next/server';

export interface WikiExportOptions {
  format: 'markdown' | 'html';
  title: string;
  projectName: string;
  teamName?: string;
  year?: number;
  sections: WikiSection[];
  includeCharts?: boolean;
  includeTables?: boolean;
  includeReferences?: boolean;
}

export interface WikiSection {
  type: 'text' | 'table' | 'chart' | 'image' | 'sequence' | 'dbtl' | 'team';
  title: string;
  content: any;
}

export async function POST(request: NextRequest) {
  try {
    const body = await request.json();
    const { format = 'markdown', title, projectName, sections, includeTables = true, includeReferences = true } = body as WikiExportOptions;

    if (format === 'markdown') {
      const markdown = generateMarkdown({ title, projectName, sections, includeTables, includeReferences });
      return new NextResponse(markdown, {
        headers: {
          'Content-Type': 'text/markdown; charset=utf-8',
          'Content-Disposition': `attachment; filename="${projectName.replace(/\s+/g, '_')}_wiki.md"`
        }
      });
    } else {
      const html = generateHTML({ title, projectName, sections, includeTables, includeReferences });
      return new NextResponse(html, {
        headers: {
          'Content-Type': 'text/html; charset=utf-8',
          'Content-Disposition': `attachment; filename="${projectName.replace(/\s+/g, '_')}_wiki.html"`
        }
      });
    }
  } catch (error) {
    return NextResponse.json(
      { error: 'Export failed', details: error instanceof Error ? error.message : 'Unknown error' },
      { status: 500 }
    );
  }
}

function generateMarkdown(options: {
  title: string;
  projectName: string;
  sections: WikiSection[];
  includeTables: boolean;
  includeReferences: boolean;
}): string {
  const { title, projectName, sections, includeTables, includeReferences } = options;
  const year = new Date().getFullYear();
  
  let md = '';
  
  // Header
  md += `# ${title}\n\n`;
  md += `**Project:** ${projectName}  \n`;
  md += `**Year:** ${year}  \n`;
  md += `**Generated by:** FluBioStack  \n`;
  md += `**Date:** ${new Date().toISOString().split('T')[0]}  \n\n`;
  md += `---\n\n`;
  
  // Table of Contents
  md += `## Table of Contents\n\n`;
  sections.forEach((section, idx) => {
    md += `${idx + 1}. [${section.title}](#${section.title.toLowerCase().replace(/\s+/g, '-')})\n`;
  });
  md += `\n---\n\n`;
  
  // Sections
  sections.forEach((section) => {
    md += `## ${section.title}\n\n`;
    md += renderMarkdownSection(section, { includeTables, includeReferences });
    md += `\n---\n\n`;
  });
  
  // References
  if (includeReferences) {
    md += `## References\n\n`;
    md += `1. FluBioStack - Synthetic Biology Research Platform\n`;
    md += `2. iGEM Competition Guidelines\n`;
  }
  
  return md;
}

function renderMarkdownSection(section: WikiSection, options: { includeTables: boolean; includeReferences: boolean }): string {
  switch (section.type) {
    case 'text':
      return section.content.text || '';
      
    case 'table':
      if (!options.includeTables || !section.content.headers || !section.content.rows) return '';
      let table = `| ${section.content.headers.join(' | ')} |\n`;
      table += `| ${section.content.headers.map(() => '---').join(' | ')} |\n`;
      section.content.rows.forEach((row: string[]) => {
        table += `| ${row.join(' | ')} |\n`;
      });
      return table;
      
    case 'sequence':
      const seq = section.content.sequence || '';
      const formatted = seq.match(/.{1,60}/g)?.join('\n') || seq;
      return `\`\`\`\n${section.content.name || 'Sequence'}\nLength: ${seq.length} bp\n\`\`\`\n\n\`\`\`\n${formatted}\n\`\`\`\n`;
      
    case 'dbtl':
      const steps = section.content.steps || [];
      let dbtl = '';
      steps.forEach((step: any) => {
        dbtl += `### ${step.phase}: ${step.date}\n\n`;
        dbtl += `**Description:** ${step.description}\n\n`;
        if (step.result) dbtl += `**Result:** ${step.result}\n\n`;
        dbtl += `**Status:** ${step.status}\n\n`;
      });
      return dbtl;
      
    case 'chart':
      return `*[Chart: ${section.title}]*\n\n**Description:** ${section.content.description || 'See visualization above'}\n`;
      
    case 'team':
      return `**Team Members:** ${section.content.members?.join(', ') || 'TBD'}\n\n**Institution:** ${section.content.institution || 'TBD'}\n`;
      
    default:
      return '';
  }
}

