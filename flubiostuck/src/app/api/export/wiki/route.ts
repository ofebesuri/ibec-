function renderHTMLSection(section: WikiSection, options: { includeTables: boolean; includeReferences: boolean }): string {
  switch (section.type) {
    case 'text':
      return `<p>${section.content.text || ''}</p>`;
      
    case 'table':
      if (!options.includeTables || !section.content.headers || !section.content.rows) return '';
      const headers = section.content.headers.map((h: string) => `<th>${h}</th>`).join('');
      const rows = section.content.rows.map((row: string[]) => 
        `<tr>${row.map(cell => `<td>${cell}</td>`).join('')}</tr>`
      ).join('\n');
      return `<table>\n<thead><tr>${headers}</tr></thead>\n<tbody>${rows}</tbody>\n</table>`;
      
    case 'sequence':
      const seq = section.content.sequence || '';
      const name = section.content.name || 'Sequence';
      const length = seq.length;
      const formatted = seq.match(/.{1,60}/g)?.join('<br>') || seq;
      return `<div>
        <span class="sequence-label">${name} | Length: ${length} bp</span>
        <div class="sequence-block">${formatted}</div>
      </div>`;
      
    case 'dbtl':
      const steps = section.content.steps || [];
      return steps.map((step: any) => {
        const statusClass = step.status === 'completed' ? 'completed' : 
                           step.status === 'in_progress' ? 'in-progress' : 'planned';
        return `<div class="dbtl-step ${statusClass}">
          <strong>${step.phase}</strong> - ${step.date}
          <p>${step.description}</p>
          ${step.result ? `<p><strong>Result:</strong> ${step.result}</p>` : ''}
          <span class="status-badge status-${statusClass.replace('-', '')}">${step.status}</span>
        </div>`;
      }).join('\n');
      
    case 'chart':
      return `<p><em>[Chart: ${section.title}]</em></p><p>${section.content.description || ''}</p>`;
      
    case 'team':
      return `<p><strong>Team Members:</strong> ${section.content.members?.join(', ') || 'TBD'}</p>
              <p><strong>Institution:</strong> ${section.content.institution || 'TBD'}</p>`;
      
    default:
      return '';
  }
}
